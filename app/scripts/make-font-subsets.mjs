/**
 * Builds the certificate fonts.
 *
 * The standard PDF fonts are WinAnsi-encoded and cannot draw "ř ě č ů ť ň ď",
 * so certificates used to print "Rehor Cízek" for Řehoř Čížek — a document that
 * names people, misspelling them. Fixing that needs a real Unicode font
 * embedded in the PDF.
 *
 * Liberation is metric-compatible with Helvetica/Courier, so switching to it
 * left the page layout — which is measured to the point, and fits one A4 —
 * where it already was.
 *
 * The full family is 1.1 MB, which is not a thing to make people download for
 * a page that is otherwise a few hundred KB. So this subsets each face to the
 * scripts a document name or a signatory name plausibly uses, and emits them
 * base64 in a generated module. Base64 rather than an asset import on purpose:
 * it resolves identically in the browser and in Node, so the tests exercise
 * the same bytes the app ships, with no bundler-specific loading path.
 *
 *   npm run fonts:subset [-- /path/to/liberation]
 *
 * Regenerating is only necessary when the ranges below change. The output is
 * committed; the OFL requires the licence to travel with it, hence OFL.txt.
 */
import fontkit from '@pdf-lib/fontkit';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const SOURCE_DIR = process.argv[2] ?? '/usr/share/fonts/truetype/liberation';
const OUT = fileURLToPath(new URL('../src/lib/fonts/', import.meta.url));

/**
 * What a file name or a person's name might be written in.
 *
 * Latin Extended-A is the one that matters here: every Czech letter the
 * standard fonts could not draw lives in it. Greek and Cyrillic are included
 * because "works anywhere" is meant literally, and they cost little. CJK is
 * deliberately absent — it would dwarf everything else, so those names still
 * fall back to a substitution, now the exception rather than the rule.
 */
const RANGES = [
  [0x0020, 0x007e], // ASCII
  [0x00a0, 0x00ff], // Latin-1 Supplement
  [0x0100, 0x017f], // Latin Extended-A — Czech, Polish, Hungarian, Baltic
  [0x0180, 0x024f], // Latin Extended-B
  [0x0370, 0x03ff], // Greek
  [0x0400, 0x04ff], // Cyrillic
  [0x2010, 0x205e], // General punctuation — dashes, quotes, ellipsis
  [0x20a0, 0x20bf], // Currency symbols
  [0x2122, 0x2122], // ™
];

const FACES = [
  ['regular', 'LiberationSans-Regular.ttf'],
  ['bold', 'LiberationSans-Bold.ttf'],
  ['mono', 'LiberationMono-Regular.ttf'],
];

/**
 * Subset by character, keeping the font a *font*.
 *
 * Not fontkit's own `createSubset()`, though it is already a dependency: that
 * one targets PDF embedding, where glyphs are addressed by id, and drops the
 * cmap. The result cannot be re-parsed — pdf-lib fails on embed with "cannot
 * read properties of undefined (reading 'records')", the missing cmap — and
 * `hasGlyphForCodePoint` has nothing to answer from. harfbuzz keeps the tables
 * a complete font needs.
 */
async function subsetOf(source) {
  const font = fontkit.create(source);

  const wanted = [];
  for (const [from, to] of RANGES) {
    for (let cp = from; cp <= to; cp++) {
      if (font.hasGlyphForCodePoint(cp)) wanted.push(String.fromCodePoint(cp));
    }
  }

  const bytes = await subsetFont(source, wanted.join(''), { targetFormat: 'truetype' });
  return { bytes, glyphs: wanted.length, total: font.numGlyphs };
}

const parts = [];
let totalBefore = 0;
let totalAfter = 0;

for (const [name, file] of FACES) {
  const source = readFileSync(`${SOURCE_DIR}/${file}`);
  const { bytes, glyphs, total } = await subsetOf(source);
  const b64 = Buffer.from(bytes).toString('base64');

  totalBefore += source.length;
  totalAfter += bytes.length;
  console.log(
    `${file.padEnd(30)} ${String(source.length).padStart(7)} -> ${String(bytes.length).padStart(6)} bytes` +
      `  (${glyphs}/${total} glyphs)`,
  );

  // One unbroken literal per face. Wrapping it into ~1,400 concatenated chunks
  // reads better but builds a binary expression tree deep enough to overflow
  // esbuild's parser: `svelte-check` died with "Maximum call stack size
  // exceeded" and a Go deadlock trace that says nothing about the cause.
  parts.push(`export const ${name} =\n  '${b64}';`);
}

const module = `// GENERATED by scripts/make-font-subsets.mjs — do not edit.
//
// Liberation Sans / Liberation Mono, subset to the ranges listed in that
// script. Licensed under the SIL Open Font License 1.1; see OFL.txt beside
// this file. Base64 so that Node and the browser load identical bytes.

${parts.join('\n\n')}
`;

writeFileSync(`${OUT}liberation.generated.ts`, module);
console.log(
  `\n${(totalBefore / 1024).toFixed(0)} KB -> ${(totalAfter / 1024).toFixed(0)} KB ` +
    `(${((totalAfter / 1024) * 1.34).toFixed(0)} KB as base64)`,
);
